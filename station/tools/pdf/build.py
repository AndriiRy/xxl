def table(rows, widths, head=True, zebra=True, valign="TOP"):
    data = [[c if not isinstance(c, str) else p(c, TBH if (head and r == 0) else TB) for c in row] for r, row in enumerate(rows)]
    t = Table(data, colWidths=[w*mm for w in widths], repeatRows=1 if head else 0)
    s = [("GRID", (0, 0), (-1, -1), 0.4, LINE), ("VALIGN", (0, 0), (-1, -1), valign),
         ("LEFTPADDING", (0, 0), (-1, -1), 4), ("RIGHTPADDING", (0, 0), (-1, -1), 4),
         ("TOPPADDING", (0, 0), (-1, -1), 2.5), ("BOTTOMPADDING", (0, 0), (-1, -1), 2.5)]
    if head: s.append(("BACKGROUND", (0, 0), (-1, 0), ACC))
    if zebra:
        for r in range(1 if head else 0, len(rows)):
            if r % 2 == 0: s.append(("BACKGROUND", (0, r), (-1, r), colors.HexColor("#f4f6f5")))
    t.setStyle(TableStyle(s)); return t

